import GLib from 'gi://GLib'
import Gio from 'gi://Gio'
import Soup from 'gi://Soup?version=3.0'
import { getInstalledPacks, packDir, NARRATORS, presetCodeForSid } from
    './voice-packs.js'
import { parseWavDuration } from './local-tts.js'
import {
    acquireReadLease, beginMutation, isMutationInProgress, waitForReaders,
} from './voice-daemon-gate.js'

// Client for the foliate-voice daemon (a fork of rttsd): one process that
// loads the sherpa-onnx models once and serves synthesis over localhost
// HTTP, instead of one engine subprocess per sentence. The daemon exits
// when the pipe we hold on its stdin closes (see its parent watchdog), so
// it can never outlive Foliate — including a force-kill of this process.

const DAEMON_CMD = 'foliate-voice'
const HEALTH_TIMEOUT_MS = 15000
const SETTLE_TIMEOUT_MS = 5000

const mutationError = () => {
    const error = new Error('a voice pack change is in progress')
    error.code = 'mutation-in-progress'
    return error
}

// Set when a pack change stopped the daemon: the next synthesis asks for a
// fresh daemon so a successful change cannot leave the old catalog in use.
let reconcilePending = false
export const daemonNeedsReconcile = () => reconcilePending
export const clearDaemonReconcile = () => { reconcilePending = false }

const gioAsync = (object, method, finish, ...args) =>
    new Promise((resolve, reject) => {
        object[method](...args, (source, result) => {
            try {
                resolve(object[finish](result))
            } catch (error) {
                reject(error)
            }
        })
    })

// Engine-specific `[[models]]` tables, one per pack id. These paths mirror
// the CLI flag templates in src/local-tts.js (ENGINE_FLAGS) and the pack
// layouts in src/voice-packs.js (expectedFiles); keep the three in sync.
const MODEL_TABLES = {
    kokoro: dir => `
[[models]]
id = "kokoro"
engine = "kokoro"
model_path = "${dir}/model.int8.onnx"
voices_path = "${dir}/voices.bin"
tokens_path = "${dir}/tokens.txt"
data_dir = "${dir}/espeak-ng-data"
lexicon_path = "${dir}/lexicon-us-en.txt,${dir}/lexicon-gb-en.txt,${dir}/lexicon-zh.txt"
dict_dir = "${dir}/dict"
`,
    piper: dir => `
[[models]]
id = "piper"
engine = "vits"
model_path = "${dir}/en_US-amy-low.onnx"
tokens_path = "${dir}/tokens.txt"
data_dir = "${dir}/espeak-ng-data"
`,
    // supertonic has no per-request language in the OpenAI-shaped API, so
    // one [[voices]] entry per supported language x narrator, labeled
    // `supertonic-xx-<preset>`.
    supertonic: dir => `
[[models]]
id = "supertonic"
engine = "supertonic"
duration_predictor_path = "${dir}/duration_predictor.int8.onnx"
text_encoder_path = "${dir}/text_encoder.int8.onnx"
vector_estimator_path = "${dir}/vector_estimator.int8.onnx"
vocoder_path = "${dir}/vocoder.int8.onnx"
tts_json_path = "${dir}/tts.json"
unicode_indexer_path = "${dir}/unicode_indexer.bin"
voice_style_path = "${dir}/voice.bin"
`,
}

const voiceTable = (label, model, sid, lang) => `
[[voices]]
label = "${label}"
model = "${model}"
sid = ${sid}
${lang ? `lang = "${lang}"\n` : ''}`

// The daemon voice label a synth request should use for a pack: the pack
// id, except supertonic which carries its language and narrator style
// (derived from the effective SID, never a display name) in the label.
export const daemonVoiceLabel = (pack, lang = 'en', sid) =>
    pack.id === 'supertonic'
        ? `supertonic-${(lang || 'en').split(/[-_]/)[0].toLowerCase()}-${
            presetCodeForSid(sid ?? pack.sid)}`
        : pack.id

export const daemonConfig = packs => {
    let toml = `
# Generated by Foliate; the foliate-voice daemon reads it at startup.
load_mode = "lazy"
concurrency_limit = 1
`
    for (const pack of packs) {
        const dir = packDir(pack.id)
        toml += MODEL_TABLES[pack.id](dir)
        if (pack.id === 'supertonic')
            for (const lang of pack.languages)
                for (const { sid } of NARRATORS)
                    toml += voiceTable(
                        daemonVoiceLabel(pack, lang, sid), pack.id, sid, lang)
        else toml += voiceTable(pack.id, pack.id, pack.sid, null)
    }
    return toml
}

// A free localhost port, probed by binding and immediately closing.
const freePort = () => {
    const socket = Gio.Socket.new(Gio.SocketFamily.IPV4, Gio.SocketType.STREAM,
        Gio.SocketProtocol.TCP)
    socket.bind(Gio.InetSocketAddress.new(
        Gio.InetAddress.new_from_string('127.0.0.1'), 0), false)
    const port = socket.get_local_address().get_port()
    socket.close()
    return port
}

export class VoiceDaemon {
    #proc = null
    #session = new Soup.Session()
    #baseUri = null
    #port = 0
    #starting = null

    // Test seam: constructing with a baseUri points the daemon at an
    // already-listening HTTP server — no subprocess is ever spawned, and
    // `running` reports true so LocalTTS treats it as the live daemon.
    constructor({ session = new Soup.Session(), baseUri = null } = {}) {
        this.#session = session
        this.#baseUri = baseUri
    }

    // truthy only while the subprocess is alive (a baseUri-backed daemon
    // is always running): the wait callback (and stop) clear #proc on exit
    get running() {
        return !!this.#baseUri || !!this.#proc
    }
    get baseUri() {
        return this.#baseUri ?? `http://127.0.0.1:${this.#port}`
    }

    // Start the daemon if not already running (resolves when /health is
    // up). Safe to call repeatedly; concurrent callers share one start.
    // While a pack change owns the mutation gate no daemon may start: the
    // catalog snapshot would race the file replacement.
    async start() {
        if (this.#baseUri) return // nothing to spawn; the server is external
        if (isMutationInProgress()) throw mutationError()
        if (this.running) return
        if (this.#starting) return this.#starting
        this.#starting = this.#start().finally(() => this.#starting = null)
        return this.#starting
    }

    // Wait for a start already in progress to settle. A start that sees the
    // closed gate stops itself; its rejection belongs to its own caller.
    async settleStartup() {
        const starting = this.#starting
        if (!starting) return
        try {
            await starting
        } catch { /* reported to the caller that requested the start */ }
    }

    async #start() {
        if (isMutationInProgress()) throw mutationError()
        const packs = getInstalledPacks()
        if (!packs.length) throw new Error('no voice packs installed')
        const cmd = GLib.getenv('FOLIATE_VOICE_CMD') ?? DAEMON_CMD
        // PATH first; then the usual user-local install location, because
        // dev shells (nix-shell) often strip ~/.local/bin from PATH
        const program = GLib.find_program_in_path(cmd)
            ?? (GLib.file_test(`${GLib.get_home_dir()}/.local/bin/${cmd}`,
                GLib.FileTest.IS_EXECUTABLE)
                ? GLib.build_filenamev([GLib.get_home_dir(), '.local/bin', cmd])
                : null)
        if (!program) throw new Error(`voice daemon not found: ${cmd}`)
        this.#port = freePort()
        const dir = GLib.build_filenamev([
            GLib.get_user_runtime_dir(), 'foliate-voice'])
        const configFile = GLib.build_filenamev([dir, `config-${this.#port}.toml`])
        GLib.mkdir_with_parents(dir, 0o700)
        GLib.file_set_contents(configFile, daemonConfig(packs))
        // STDIN_PIPE: we keep the write end; the daemon watches it and
        // exits when it closes, so it dies with Foliate — SIGKILL included
        this.#proc = Gio.Subprocess.new(
            [program, '--config', configFile, '--load-mode', 'lazy',
                '--log-format', 'json', '--bind-port', String(this.#port)],
            Gio.SubprocessFlags.STDIN_PIPE |
                Gio.SubprocessFlags.STDOUT_SILENCE |
                Gio.SubprocessFlags.STDERR_PIPE)
        // STDIN_PIPE fd closes when Foliate exits (SIGKILL included); the
        // daemon watches it, so nothing here needs explicit bookkeeping
        const stderr = drain(this.#proc.get_stderr_pipe())
        this.#proc.wait_async(null, proc => {
            // unexpected exit: clear state and surface why it died
            if (this.#proc === proc) {
                this.#proc = null
                stderr.then(text => {
                    if (text?.trim())
                        console.warn(`voice daemon exited: ${text.trim()}`)
                }).catch(console.debug)
            }
        })
        await this.#waitHealthy()
        // a pack change closed the gate while the daemon was becoming
        // healthy: stop it before it can serve the catalog being replaced
        if (isMutationInProgress()) {
            await this.stop()
            throw mutationError()
        }
    }

    async #waitHealthy() {
        const deadline = Date.now() + HEALTH_TIMEOUT_MS
        // any error before the deadline just means "not up yet"
        while (Date.now() < deadline) {
            if (!this.running) throw new Error('voice daemon exited during startup')
            try {
                const message = Soup.Message.new('GET', `${this.baseUri}/health`)
                await gioAsync(this.#session, 'send_async', 'send_finish',
                    message, GLib.PRIORITY_DEFAULT, null)
                if (message.get_status() === Soup.Status.OK) return
            } catch { /* not up yet */ }
            await new Promise(resolve => GLib.timeout_add(
                GLib.PRIORITY_DEFAULT, 50,
                () => (resolve(), GLib.SOURCE_REMOVE)))
        }
        this.stop()
        throw new Error('voice daemon did not become healthy in time')
    }

    // Synthesize one sentence through the daemon; the response is a whole
    // wav, staged at partPath like the CLI engine's output. The selected
    // narrator (sid) chooses the label; the label maps to a [[voices]]
    // entry that carries the same sid from the preset catalogue.
    async synth(...args) {
        const release = acquireReadLease()
        try {
            return await this.#synthUnlocked(...args)
        } finally {
            release()
        }
    }

    async #synthUnlocked(text, partPath, pack, { lang, sid, cancellable = null } = {}) {
        const label = daemonVoiceLabel(pack, lang, sid)
        const body = JSON.stringify({
            input: text,
            voice: label,
            response_format: 'wav',
        })
        const message = Soup.Message.new('POST', `${this.baseUri}/v1/audio/speech`)
        message.set_request_body_from_bytes('application/json',
            new GLib.Bytes(new TextEncoder().encode(body)))
        // response_format=wav is a whole body, so read it in one call
        const bytes = await gioAsync(this.#session, 'send_and_read_async',
            'send_and_read_finish', message, GLib.PRIORITY_DEFAULT, cancellable)
        if (message.get_status() !== Soup.Status.OK)
            throw new Error(`voice daemon returned HTTP ${message.get_status()}`)
        if (!bytes?.get_size())
            throw new Error('voice daemon returned no audio')
        const out = Gio.File.new_for_path(partPath)
            .replace(null, false, Gio.FileCreateFlags.NONE, cancellable)
        try {
            let offset = 0
            const data = bytes.get_data()
            while (offset < data.length) {
                const written = await gioAsync(out, 'write_bytes_async',
                    'write_bytes_finish', new GLib.Bytes(data.subarray(offset)),
                    GLib.PRIORITY_DEFAULT, cancellable)
                if (!written) throw new Error('voice daemon response could not be written')
                offset += written
            }
        } finally {
            try { out.close(null) } catch { /* best effort */ }
        }
        return parseWavDuration(partPath)
    }

    // Stop the daemon gracefully (SIGTERM); resolves true when it exited,
    // false when it refused or was already gone.
    async stop() {
        const proc = this.#proc
        if (!proc) return true
        this.#proc = null
        // closing our end first would trip the daemon's parent watchdog
        // before SIGTERM lands; just send the signal and let the pipe close
        // with this process (the watchdog covers a force-kill anyway)
        proc.send_signal(15)
        const exited = await new Promise(resolve => {
            const timeout = GLib.timeout_add_seconds(GLib.PRIORITY_DEFAULT, 5,
                () => (resolve(false), GLib.SOURCE_REMOVE))
            proc.wait_async(null, () => {
                GLib.source_remove(timeout)
                resolve(true)
            })
        })
        return exited
    }
}

const drain = stream => new Promise((resolve, reject) => {
    const chunks = []
    const decode = chunks => {
        const all = new Uint8Array(
            chunks.reduce((size, chunk) => size + chunk.length, 0))
        let offset = 0
        for (const chunk of chunks) {
            all.set(chunk, offset)
            offset += chunk.length
        }
        return new TextDecoder().decode(all)
    }
    const read = () => {
        stream.read_bytes_async(64 * 1024, GLib.PRIORITY_DEFAULT, null,
            (source, result) => {
                try {
                    const bytes = source.read_bytes_finish(result)
                    if (bytes.get_size() === 0) return resolve(decode(chunks))
                    chunks.push(bytes.get_data())
                    read()
                } catch (error) {
                    reject(error)
                }
            })
    }
    read()
})

let daemon = null
export const getVoiceDaemon = () => daemon ??= new VoiceDaemon()

export const startVoiceDaemon = () => getVoiceDaemon().start()
    .catch(e => console.warn(`voice daemon not started: ${e.message}`))

export const stopVoiceDaemon = async () => {
    if (!daemon?.running) return true
    const exited = await daemon.stop()
    if (!exited) console.warn('voice daemon did not exit; it will shut down when Foliate closes')
    return exited
}

// Prepare a voice pack file change. Closing the gate first blocks new
// native readers and lazy daemon startup; the daemon start already in
// progress settles (and aborts itself), this app's daemon stops, and the
// CLI/probe readers still holding a lease are awaited. Resolves with the
// release function the caller MUST invoke in a finally block after
// publication or rollback — the gate deliberately covers both. A failed
// preparation releases its own gate before rejecting.
export const prepareVoicePackChange = async ({
    stopDaemon = null,
    settleTimeoutMs = SETTLE_TIMEOUT_MS,
} = {}) => {
    const release = beginMutation()
    try {
        const voiceDaemon = getVoiceDaemon()
        await voiceDaemon.settleStartup()
        const stopped = stopDaemon
            ? await stopDaemon(voiceDaemon)
            : await voiceDaemon.stop()
        if (stopped === false)
            throw new Error('voice daemon did not stop; refusing to change packs')
        await waitForReaders(settleTimeoutMs)
        reconcilePending = true
        return release
    } catch (error) {
        release()
        throw error
    }
}
